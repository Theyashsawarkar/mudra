#!/usr/bin/env python3
"""Writes this tool's keys from its keymap (<tool>/vim.py) into the two places
that list them: the `# keybind:` lines in <tool>/__init__.py (Vayu's keybinding
search reads them; the mode follows the scope, ":normal" / ":insert") and the
key tables in README.md. `--check` fails when either is out of date (CI runs it).

The keymap uses Vyom's keys module (vyom/keys.py, pure Python): it's found
on PYTHONPATH, in $VYOM_CORE, next to this checkout (../vyom) or in the
installed Vyom (~/.local/share/vyom/core).
"""
import importlib.util
import os
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOL = tomllib.load(open(ROOT / "plugin.toml", "rb"))["name"]


def find_vyom():
    try:
        import vyom.keys  # noqa: F401
        return
    except ImportError:
        pass
    for d in (os.environ.get("VYOM_CORE"), ROOT.parent / "vyom",
              pathlib.Path.home() / ".local/share/vyom/core"):
        if d and (pathlib.Path(d) / "vyom" / "keys.py").exists():
            sys.path.insert(0, str(d))
            return
    sys.exit("can't find Vyom's vyom/keys.py: set VYOM_CORE to a Vyom checkout")


find_vyom()
from vyom import keys as K  # noqa: E402

spec = importlib.util.spec_from_file_location(f"{TOOL}_vim", ROOT / TOOL / "vim.py")
vim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vim)


def doc(b):
    """(keys as written, description) of a shown key: a Bind, or a
    ("Alt+1..9", "…") pair for a range the tool handles in its key()."""
    if isinstance(b, tuple):
        return b
    return (K.spell(b.seq), b.desc) if not b.hidden and b.desc else None


def sections():
    """(scope, mode, title, [(keys, description)]) in reading order."""
    return [(scope, mode, title, [d for d in map(doc, bs) if d])
            for scope, mode, title, bs in vim.SECTIONS]


def annotations():
    lines = [f"# KEYBINDS (generated from {TOOL}/vim.py by scripts/keybinds.py; don't edit by hand)"]
    for scope, mode, _, ds in sections():
        suffix = f":{mode}" if mode in ("normal", "insert", "visual", "command") else ""
        lines += [f"# keybind: Vyom/{scope}{suffix} | {k} | {d}" for k, d in ds]
    lines.append("# END KEYBINDS")
    return "\n".join(lines) + "\n"


def tables():
    core = ("Vyom's keys work too (every vim tool has them): `?` and `Space ?` list every key, "
            "`Space Space` is the palette, `j` / `k` move, `gg` / `G` jump, `/` searches again, "
            "`H` / `L` switch tabs, `q` closes, `Space u f` is fullscreen, `Esc` steps back.")
    out = [f"<!-- KEYS (generated by scripts/keybinds.py from {TOOL}/vim.py) -->", "", core, ""]
    for _, _, title, bs in sections():
        if not bs:
            continue
        out += [f"**{title}**", "", "| Key | Action |", "|---|---|"]
        out += [f"| `{k}` | {d} |" for k, d in bs]
        out.append("")
    out.append("<!-- END KEYS -->")
    return "\n".join(out)


def splice(text, start, end, new):
    a = text.index(start)
    b = text.index(end, a) + len(end)
    if new.endswith("\n") and text[b:b + 1] == "\n":
        b += 1
    return text[:a] + new + text[b:]


def main():
    init = ROOT / TOOL / "__init__.py"
    readme = ROOT / "README.md"
    new_init = splice(init.read_text(), "# KEYBINDS", "# END KEYBINDS", annotations())
    new_readme = splice(readme.read_text(), "<!-- KEYS", "<!-- END KEYS -->", tables())
    stale = [p.name for p, t in ((init, new_init), (readme, new_readme)) if p.read_text() != t]
    if "--check" in sys.argv:
        if stale:
            sys.exit(f"out of date: {', '.join(stale)} (run scripts/keybinds.py)")
        print("keys are up to date")
        return
    init.write_text(new_init)
    readme.write_text(new_readme)
    print("wrote", ", ".join(stale) or "nothing (up to date)")


if __name__ == "__main__":
    main()
